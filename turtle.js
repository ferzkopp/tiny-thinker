// Mini-Logo / turtle graphics extractor, parser, bounded interpreter and SVG renderer.
// Safe by construction: interprets a small fixed command vocabulary, never eval/Function.

const SVG_NS = 'http://www.w3.org/2000/svg';
const STAGE_SIZE = 240;
const HALF = STAGE_SIZE / 2;
const MAX_REPEAT = 360;
const MAX_STEPS = 2000;
const MAX_COORD = 5000;

export const TURTLE_COLORS = {
  blue: '#2f6fde',
  red: '#d63939',
  green: '#1a7a43',
  orange: '#d97706',
  purple: '#7c3aed',
  pink: '#db2777',
  teal: '#0d9488',
  gold: '#b45309',
  black: '#1c2430',
  gray: '#5d6b7c',
  grey: '#5d6b7c',
};

const ALIASES = {
  FD: 'FD', FORWARD: 'FD', FW: 'FD', MOVE: 'FD',
  BK: 'BK', BACK: 'BK', BACKWARD: 'BK', BW: 'BK',
  RT: 'RT', RIGHT: 'RT', TURN: 'RT',
  LT: 'LT', LEFT: 'LT',
  PU: 'PU', PENUP: 'PU', UP: 'PU',
  PD: 'PD', PENDOWN: 'PD', DOWN: 'PD',
  COLOR: 'COLOR', COLOUR: 'COLOR', SETPC: 'COLOR', PEN: 'COLOR', PENCOLOR: 'COLOR',
  WIDTH: 'WIDTH', SETPW: 'WIDTH', PENWIDTH: 'WIDTH', PENSIZE: 'WIDTH', SIZE: 'WIDTH',
  HOME: 'HOME', CENTER: 'HOME',
  CLEAR: 'CLEAR', CS: 'CLEAR', CLEARSCREEN: 'CLEAR', RESET: 'CLEAR',
  REPEAT: 'REPEAT',
};

const COMMAND_HELP = 'FD, BK, RT, LT, PU, PD, COLOR, WIDTH, HOME, CLEAR, or REPEAT n [ ... ]';

/**
 * Extracts turtle code from a model reply: prefers a fenced block if present,
 * otherwise keeps lines that start with a known turtle command or bracket.
 * @param {string} text Raw assistant reply.
 * @returns {string} Cleaned turtle program.
 */
export function extractTurtleCode(text) {
  if (!text) return '';
  // Stop before any echoed "User:" or "Question:" continuation generated by small models.
  const source = String(text).replace(/\r\n?/g, '\n').split(/\n\s*(?:User|Human|Question|Prompt):/i)[0].split(/\bUser:/i)[0];
  const fences = [...source.matchAll(/```(?:logo|turtle|txt|plaintext)?\s*\n([\s\S]*?)```/gi)];
  if (fences.length) {
    const fromFences = fences.map((m) => cleanLines(m[1], { filterProse: true })).filter(Boolean).join('\n').trim();
    if (fromFences) return fromFences;
  }
  const unclosed = source.match(/```(?:logo|turtle|txt|plaintext)?\s*\n([\s\S]*)$/i);
  if (unclosed) {
    const fromUnclosed = cleanLines(unclosed[1], { filterProse: true }).trim();
    if (fromUnclosed) return fromUnclosed;
  }
  const byLines = cleanLines(source, { filterProse: true }).trim();
  if (byLines) return byLines;
  // Last resort: scan for inline REPEAT or FD/BK command runs embedded inside a prose sentence.
  const inline = source.match(/\b(?:COLOR\s+[a-z#0-9]+\s+)?(?:REPEAT\s+\d+\s*\[[^\]]+\]|(?:(?:FD|FORWARD|BK|BACK|RT|RIGHT|LT|LEFT)\s+-?\d+(?:\.\d+)?(?:\s+|\s*,\s*|$)){2,})/i);
  return inline ? cleanLines(inline[0], { filterProse: true }).trim() : '';
}

/**
 * Cleans common small-model formatting habits (list numbers, comments, `FD(50)`).
 * When `filterProse` is true, keeps only lines that start with a known turtle command or bracket,
 * falling back to the raw lines only if none matched so the parser can still report a helpful error.
 */
function cleanLines(block, { filterProse = false } = {}) {
  const rawLines = block.split('\n').map((line) => line
    .replace(/^\s*(?:[-*•]|\d+[.)])\s+/, '')
    .replace(/^\s*(?:[a-z][a-z0-9 ]{0,18}:\s+)(?=(?:FD|FORWARD|BK|BACK|RT|RIGHT|LT|LEFT|PU|PD|COLOR|COLOUR|WIDTH|HOME|CLEAR|REPEAT)\b)/i, '')
    .replace(/^\s*(?:t|turtle)\.(forward|fd|backward|bk|back|right|rt|left|lt|penup|pu|pendown|pd|pencolor|color|width|pensize|home|clear)\s*\(([^)]*)\)/i, (_, fn, arg) => `${fn.toUpperCase()} ${arg}`)
    .replace(/\s*(?:;|\/\/|#(?![0-9a-f]{3,6}\b)).*$/i, '')
    .replace(/\s+\b(?:in|using|with)\s+[a-z]+\s*\.?$/i, '')
    .trim()).filter(Boolean);

  if (!filterProse) return rawLines.join('\n');

  const looksLikeCommand = (line) => {
    if (/^\[\s*(?:FD|FORWARD|BK|BACK|RT|RIGHT|LT|LEFT|PU|PD|COLOR|COLOUR|WIDTH|HOME|CLEAR|REPEAT)\b/i.test(line)) return true;
    if (/^\]$/.test(line)) return true;
    const first = line.match(/^([a-zA-Z]+)/)?.[1]?.toUpperCase();
    return Boolean(first && ALIASES[first]);
  };
  const commandLines = rawLines.filter(looksLikeCommand);
  // Deduplicate runaway identical consecutive lines (>4 repeats) when a small model loops until maxTokens.
  const deduped = [];
  let runCount = 0;
  for (const line of commandLines) {
    if (line === deduped[deduped.length - 1]) {
      runCount += 1;
      if (runCount <= 4) deduped.push(line);
    } else {
      runCount = 1;
      deduped.push(line);
    }
  }
  if (deduped.length > 1 && /^(?:FD|FORWARD|BK|BACK|RT|RIGHT|LT|LEFT|COLOR|COLOUR|WIDTH|REPEAT)$/i.test(deduped[deduped.length - 1].split(/\s+/).pop())) {
    const trimmedLast = deduped[deduped.length - 1].replace(/\s+(?:FD|FORWARD|BK|BACK|RT|RIGHT|LT|LEFT|COLOR|COLOUR|WIDTH|REPEAT)$/i, '').trim();
    if (trimmedLast) deduped[deduped.length - 1] = trimmedLast;
    else deduped.pop();
  }
  return deduped.join('\n');
}

/**
 * Tokenizes a turtle program while keeping 1-based line numbers for diagnostics.
 * Normalizes `FD(50)`, `FD: 50`, and commas into whitespace-separated tokens.
 * @param {string} code
 * @returns {{token: string, line: number}[]}
 */
function tokenize(code) {
  const tokens = [];
  const lines = String(code || '').replace(/\r\n?/g, '\n').split('\n');
  for (let i = 0; i < lines.length; i++) {
    const lineNo = i + 1;
    const cleaned = lines[i]
      .replace(/^\s*(?:[-*•]|\d+[.)])\s+/, '')
      .replace(/\s*(?:;|\/\/|#(?![0-9a-f]{3,6}\b)).*$/i, '')
      .replace(/\[/g, ' [ ')
      .replace(/\]/g, ' ] ')
      .replace(/[(),:]/g, ' ')
      .trim();
    if (!cleaned) continue;
    for (const part of cleaned.split(/\s+/)) {
      if (part) tokens.push({ token: part, line: lineNo });
    }
  }
  return tokens;
}

/**
 * Parses a turtle program into an AST and collects syntax errors with line numbers.
 * Supports single-level or nested `REPEAT n [ ... ]`.
 * @param {string} code
 * @returns {{ast: object[], errors: string[]}}
 */
export function parseTurtle(code) {
  const tokens = tokenize(code);
  const errors = [];
  let pos = 0;

  function parseBlock(depth) {
    const items = [];
    while (pos < tokens.length) {
      const { token, line } = tokens[pos];
      if (token === ']') {
        if (depth > 0) {
          pos += 1;
          return items;
        }
        errors.push(`Line ${line}: unexpected "]" without a matching REPEAT [.`);
        pos += 1;
        continue;
      }
      if (token === '[') {
        errors.push(`Line ${line}: unexpected "[" (use REPEAT count [ commands ]).`);
        pos += 1;
        continue;
      }

      const canonical = ALIASES[token.toUpperCase()];
      if (!canonical) {
        errors.push(`Line ${line}: unknown command "${token}". Valid commands: ${COMMAND_HELP}.`);
        pos += 1;
        continue;
      }
      pos += 1;

      if (canonical === 'PU' || canonical === 'PD' || canonical === 'HOME' || canonical === 'CLEAR') {
        items.push({ op: canonical, line });
        continue;
      }

      if (canonical === 'FD' || canonical === 'BK' || canonical === 'RT' || canonical === 'LT' || canonical === 'WIDTH') {
        const next = tokens[pos];
        const value = next ? Number(next.token) : NaN;
        if (!next || !Number.isFinite(value)) {
          errors.push(`Line ${line}: ${canonical} needs a number after it (for example: ${canonical} ${canonical === 'WIDTH' ? 2 : 50}).`);
          continue;
        }
        pos += 1;
        items.push({ op: canonical, value, line });
        continue;
      }

      if (canonical === 'COLOR') {
        const next = tokens[pos];
        if (!next || next.token === '[' || next.token === ']') {
          errors.push(`Line ${line}: COLOR needs a colour name (blue, red, green, orange, purple, pink, teal, gold, black) or #hex.`);
          continue;
        }
        const raw = next.token.toLowerCase();
        const color = TURTLE_COLORS[raw] || (/^#[0-9a-f]{3,6}$/i.test(raw) ? raw : null);
        if (!color) {
          errors.push(`Line ${line}: unknown colour "${next.token}". Choose ${Object.keys(TURTLE_COLORS).slice(0, 9).join(', ')}.`);
          pos += 1;
          continue;
        }
        pos += 1;
        items.push({ op: 'COLOR', value: color, name: raw, line });
        continue;
      }

      if (canonical === 'REPEAT') {
        const countTok = tokens[pos];
        const count = countTok ? Math.floor(Number(countTok.token)) : NaN;
        if (!countTok || !Number.isFinite(count) || count < 1) {
          errors.push(`Line ${line}: REPEAT needs a whole number >= 1 before "[ ... ]".`);
          continue;
        }
        pos += 1;
        const openTok = tokens[pos];
        if (!openTok || openTok.token !== '[') {
          errors.push(`Line ${line}: REPEAT ${count} must be followed by "[ commands ]".`);
          continue;
        }
        pos += 1;
        const body = parseBlock(depth + 1);
        if (!body.length) {
          errors.push(`Line ${line}: REPEAT ${count} [ ... ] has no commands inside the brackets.`);
        }
        items.push({ op: 'REPEAT', count: Math.min(count, MAX_REPEAT), body, line });
      }
    }
    if (depth > 0) {
      const lastLine = tokens[tokens.length - 1]?.line || 1;
      errors.push(`Line ${lastLine}: missing closing "]" for REPEAT.`);
    }
    return items;
  }

  const ast = parseBlock(0);
  if (!tokens.length) {
    errors.push(`No turtle commands found. Write commands like: REPEAT 4 [ FD 60 RT 90 ]`);
  }
  return { ast, errors };
}

/**
 * Parses and executes turtle code within safe step and coordinate bounds.
 * Heading 0 points up (North); 90 points right (East), matching standard Logo.
 * @param {string} code
 * @returns {{code: string, ast: object[], segments: object[], steps: number,
 *   turtle: {x: number, y: number, angle: number, penDown: boolean, color: string, width: number},
 *   errors: string[]}}
 */
export function runTurtle(code) {
  const { ast, errors } = parseTurtle(code);
  let segments = [];
  let steps = 0;
  const turtle = { x: 0, y: 0, angle: 0, penDown: true, color: TURTLE_COLORS.blue, width: 2.5 };

  function exec(nodes) {
    for (const node of nodes) {
      if (steps >= MAX_STEPS) {
        errors.push(`Stopped at ${MAX_STEPS} steps so the drawing cannot freeze the page.`);
        return;
      }
      steps += 1;
      switch (node.op) {
        case 'FD':
        case 'BK': {
          const dist = node.op === 'FD' ? node.value : -node.value;
          const rad = (turtle.angle * Math.PI) / 180;
          const nx = Math.max(-MAX_COORD, Math.min(MAX_COORD, turtle.x + Math.sin(rad) * dist));
          const ny = Math.max(-MAX_COORD, Math.min(MAX_COORD, turtle.y - Math.cos(rad) * dist));
          if (turtle.penDown) {
            segments.push({ x1: turtle.x, y1: turtle.y, x2: nx, y2: ny, color: turtle.color, width: turtle.width });
          }
          turtle.x = nx;
          turtle.y = ny;
          break;
        }
        case 'RT':
          turtle.angle = (turtle.angle + node.value) % 360;
          break;
        case 'LT':
          turtle.angle = (turtle.angle - node.value) % 360;
          break;
        case 'PU':
          turtle.penDown = false;
          break;
        case 'PD':
          turtle.penDown = true;
          break;
        case 'COLOR':
          turtle.color = node.value;
          break;
        case 'WIDTH':
          turtle.width = Math.max(1, Math.min(12, node.value));
          break;
        case 'HOME':
          turtle.x = 0;
          turtle.y = 0;
          turtle.angle = 0;
          break;
        case 'CLEAR':
          segments = [];
          turtle.x = 0;
          turtle.y = 0;
          turtle.angle = 0;
          break;
        case 'REPEAT':
          for (let i = 0; i < node.count && steps < MAX_STEPS; i++) exec(node.body);
          break;
      }
    }
  }

  exec(ast);
  return { code: String(code || '').trim(), ast, segments, steps, turtle, errors };
}

/** Creates an SVG element with attributes. */
function svgEl(tag, attrs = {}) {
  const node = document.createElementNS(SVG_NS, tag);
  for (const [key, value] of Object.entries(attrs)) node.setAttribute(key, String(value));
  return node;
}

/**
 * Renders the result of runTurtle() as a 240x240 SVG element, auto-fitting large drawings into view.
 * @param {ReturnType<typeof runTurtle>} result
 * @returns {SVGSVGElement}
 */
export function renderTurtleSvg(result) {
  let minX = 0;
  let maxX = 0;
  let minY = 0;
  let maxY = 0;
  for (const seg of result.segments) {
    minX = Math.min(minX, seg.x1, seg.x2);
    maxX = Math.max(maxX, seg.x1, seg.x2);
    minY = Math.min(minY, seg.y1, seg.y2);
    maxY = Math.max(maxY, seg.y1, seg.y2);
  }
  minX = Math.min(minX, result.turtle.x);
  maxX = Math.max(maxX, result.turtle.x);
  minY = Math.min(minY, result.turtle.y);
  maxY = Math.max(maxY, result.turtle.y);

  const cx = (minX + maxX) / 2;
  const cy = (minY + maxY) / 2;
  const halfSpan = Math.max(80, (maxX - minX) / 2, (maxY - minY) / 2) * 1.15 + 14;
  const viewMinX = Math.round(cx - halfSpan);
  const viewMinY = Math.round(cy - halfSpan);
  const viewSize = Math.round(halfSpan * 2);
  const strokeScale = viewSize / STAGE_SIZE;

  const svg = svgEl('svg', {
    class: 'turtle-canvas',
    viewBox: `${viewMinX} ${viewMinY} ${viewSize} ${viewSize}`,
    width: STAGE_SIZE,
    height: STAGE_SIZE,
    role: 'img',
    'aria-label': result.segments.length
      ? `Turtle drawing with ${result.segments.length} line segments`
      : 'Empty turtle stage',
  });

  // Subtle axes and start dot so students can see (0, 0) and heading direction.
  svg.append(
    svgEl('line', {
      x1: viewMinX, y1: 0, x2: viewMinX + viewSize, y2: 0,
      class: 'turtle-axis',
      'stroke-width': (1 * strokeScale).toFixed(2),
      'stroke-dasharray': `${(3 * strokeScale).toFixed(1)} ${(3 * strokeScale).toFixed(1)}`,
    }),
    svgEl('line', {
      x1: 0, y1: viewMinY, x2: 0, y2: viewMinY + viewSize,
      class: 'turtle-axis',
      'stroke-width': (1 * strokeScale).toFixed(2),
      'stroke-dasharray': `${(3 * strokeScale).toFixed(1)} ${(3 * strokeScale).toFixed(1)}`,
    }),
    svgEl('circle', { cx: 0, cy: 0, r: (3 * strokeScale).toFixed(2), class: 'turtle-origin' }),
  );

  for (const seg of result.segments) {
    svg.append(svgEl('line', {
      x1: seg.x1.toFixed(2),
      y1: seg.y1.toFixed(2),
      x2: seg.x2.toFixed(2),
      y2: seg.y2.toFixed(2),
      stroke: seg.color,
      'stroke-width': (seg.width * strokeScale).toFixed(2),
      'stroke-linecap': 'round',
    }));
  }

  // Turtle cursor triangle pointing in `turtle.angle` direction.
  const size = 6.5 * strokeScale;
  const { x, y, angle, color } = result.turtle;
  const cursor = svgEl('polygon', {
    points: `0,${-size} ${size * 0.65},${size * 0.75} 0,${size * 0.35} ${-size * 0.65},${size * 0.75}`,
    transform: `translate(${x.toFixed(2)} ${y.toFixed(2)}) rotate(${angle.toFixed(1)})`,
    fill: color,
    'stroke-width': (1.2 * strokeScale).toFixed(2),
    class: 'turtle-cursor',
  });
  svg.append(cursor);
  return svg;
}
